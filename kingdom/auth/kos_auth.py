# ---------------------------------------------------------------- constants

STATE_DIR = Path(os.environ.get("KOS_AUTH_DIR", "/home/liamb/kos-auth"))
ACCOUNTS_FILE = "accounts.json"
AUDIT_FILE = "audit.jsonl"
ADMIN_FILE = "admin.token"

SCRYPT_N = 1 << 15
SCRYPT_R = 8
SCRYPT_P = 1
SCRYPT_DKLEN = 32
# 128 * N * r bytes is the working set; Python's default cap (32 MiB) is exactly on the line.
SCRYPT_MAXMEM = 96 * 1024 * 1024

SECRET_ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"  # no I/O/0/1 — it gets read off a screen
SECRET_GROUPS = 4
SECRET_GROUP_LEN = 5

FAIL_LIMIT = 5
LOCKOUT_BASE_SECONDS = 30
IDENTITY_TTL_SECONDS = 300


def now() -> float:
    return time.time()


def canonical(payload: dict[str, Any]) -> str:
    return json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


# ---------------------------------------------------------------- identity


@dataclass(frozen=True)
class Identity:
    """Who a connecting device is, according to the tailnet itself."""

    user_id: str
    node_id: str
    login: str
    machine: str

    @property
    def display_default(self) -> str:
        """A readable handle — shared devices often report no machine name at all."""
        if self.machine:
            return self.machine.split(".")[0]
        local = self.login.split("@")[0] if "@" in self.login else self.login
        return local or f"tailnet-{self.node_id[-6:]}"

    @property
    def fingerprint(self) -> str:
        return f"{self.user_id}/{self.node_id}"


def parse_whois(text: str) -> Identity | None:
    """Parse `tailscale whois` output. Blocks look like:

        Machine:
          Name:          beelink.tail96c9e1.ts.net
          ID:            nESEeBiRPP11CNTRL
          Addresses:     [100.102.189.126/32]
        User:
          Name:     liamdev631@gmail.com
          ID:       7230364925941255
    """
    machine_name = ""
    machine_id = ""
    login = ""
    user_id = ""
    section = ""
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.endswith(":") and ":" not in line[:-1] and line[:-1] in ("Machine", "User"):
            section = line[:-1]
            continue
        if ":" not in line:
            continue
        key, _, value = line.partition(":")
        key = key.strip()
        value = value.strip()
        if section == "Machine":
            if key == "Name":
                machine_name = value
            elif key == "ID":
                machine_id = value
        elif section == "User":
            if key == "Name":
                login = value
            elif key == "ID":
                user_id = value
    if not user_id:
        return None
    return Identity(user_id=user_id, node_id=machine_id, login=login, machine=machine_name)


class IdentityResolver:
    """Looks up tailnet identity for an IP, with a cache so a reconnect is free."""

    def __init__(self, runner: Callable[[list[str]], str] | None = None, ttl: int = IDENTITY_TTL_SECONDS):
        self._runner = runner or self._run_whois
        self._ttl = ttl
        self._cache: dict[str, tuple[float, Identity | None]] = {}

    @staticmethod
    def _run_whois(argv: list[str]) -> str:
        try:
            result = subprocess.run(argv, capture_output=True, text=True, timeout=8)
        except (subprocess.TimeoutExpired, FileNotFoundError) as exc:
            raise IdentityError(f"tailscale lookup failed: {exc}") from exc
        if result.returncode != 0:
            raise IdentityError("not a tailnet address" if "no match" in result.stderr.lower()
                                else result.stderr.strip() or "tailscale lookup failed")
        return result.stdout

    def resolve(self, ip: str) -> Identity:
        cached = self._cache.get(ip)
        if cached and now() - cached[0] < self._ttl:
            if cached[1] is None:
                raise IdentityError("not a tailnet address")
            return cached[1]
        identity = parse_whois(self._runner(["tailscale", "whois", ip]))
        if identity is None:
            self._cache[ip] = (now(), None)
            raise IdentityError("not a tailnet address")
        self._cache[ip] = (now(), identity)
        return identity


class IdentityError(RuntimeError):
    pass


