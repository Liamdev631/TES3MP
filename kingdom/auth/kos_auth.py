#!/usr/bin/env python3
"""Kingdom of Science — tailnet-identity accounts for the TES3MP world.

One rule shapes everything here: a player is who the *network* says they are, never who they claim
to be. Tailscale gives every device a stable node id and every account a stable user id; the game
server hands us the connecting player's IP and we ask `tailscale whois` who that is. So the
username is not chosen, not typed, and not forgeable by anyone who cannot sit on that device.

The password is the second factor: generated by this service the first time an identity connects,
shown to that player once so they can copy it somewhere safe, and thereafter stored only as a
scrypt hash. Nothing here ever writes a plaintext secret to disk, and every state change is
appended to a hash-chained audit log so tampering after the fact is detectable.

Integration: the TES3MP server's Lua reaches this through the command line — one JSON object on
stdout, no daemon required, no socket the game engine has to learn.

    python3 kos_auth.py identify --ip 100.109.247.50
    python3 kos_auth.py enroll  --ip 100.109.247.50 --display robby
    python3 kos_auth.py verify  --ip 100.109.247.50 --secret XXXX-XXXX-XXXX
    python3 kos_auth.py status
    python3 kos_auth.py audit-verify
"""

