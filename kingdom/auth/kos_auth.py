def hash_secret(secret: str, salt: bytes | None = None) -> tuple[str, str, dict[str, int]]:
    salt = salt or secrets.token_bytes(16)
    digest = hashlib.scrypt(
        secret.encode("utf-8"),
        salt=salt,
        n=SCRYPT_N,
        r=SCRYPT_R,
        p=SCRYPT_P,
        dklen=SCRYPT_DKLEN,
        maxmem=SCRYPT_MAXMEM,
    )
    params = {"kdf": "scrypt", "n": SCRYPT_N, "r": SCRYPT_R, "p": SCRYPT_P, "dklen": SCRYPT_DKLEN}
    return salt.hex(), digest.hex(), params


def check_secret(secret: str, salt_hex: str, hash_hex: str, params: dict[str, int]) -> bool:
    digest = hashlib.scrypt(
        secret.encode("utf-8"),
        salt=bytes.fromhex(salt_hex),
        n=int(params.get("n", SCRYPT_N)),
        r=int(params.get("r", SCRYPT_R)),
        p=int(params.get("p", SCRYPT_P)),
        dklen=int(params.get("dklen", SCRYPT_DKLEN)),
        maxmem=SCRYPT_MAXMEM,
    )
    return hmac.compare_digest(digest.hex(), hash_hex)


def new_secret() -> str:
    groups = ["".join(secrets.choice(SECRET_ALPHABET) for _ in range(SECRET_GROUP_LEN))
              for _ in range(SECRET_GROUPS)]
    return "-".join(groups)


class AuditLog:
    """Append-only JSONL where each entry carries the hash of the entry before it.

    Anyone editing, reordering or deleting a line breaks every hash after it, which is what makes
    tampering visible rather than silent. (It cannot *prevent* tampering when the tamperer runs as
    the same OS user; that needs a separate UID — see docs/ARCHITECTURE.md.)
    """

    GENESIS = "0" * 64

    def __init__(self, path: Path):
        self.path = path

    def _last_hash(self) -> str:
        if not self.path.exists():
            return self.GENESIS
        last = self.GENESIS
        with self.path.open("r", encoding="utf-8") as handle:
            for line in handle:
                line = line.strip()
                if not line:
                    continue
                try:
                    last = json.loads(line).get("hash", self.GENESIS)
                except json.JSONDecodeError:
                    continue
        return last

    def append(self, event: str, **fields: Any) -> dict[str, Any]:
        entry = {"ts": round(now(), 3), "event": event, **fields}
        entry["prev"] = self._last_hash()
        entry["hash"] = hashlib.sha256((entry["prev"] + canonical(entry)).encode("utf-8")).hexdigest()
        self.path.parent.mkdir(parents=True, exist_ok=True)
        with self.path.open("a", encoding="utf-8") as handle:
            handle.write(canonical(entry) + "\n")
            handle.flush()
            os.fsync(handle.fileno())
        return entry

    def verify(self) -> tuple[bool, int, str | None]:
        if not self.path.exists():
            return True, 0, None
        prev = self.GENESIS
        count = 0
        for line in self.path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line:
                continue
            count += 1
            try:
                entry = json.loads(line)
            except json.JSONDecodeError:
                return False, count, f"line {count} is not JSON"
            recorded = entry.pop("hash", None)
            if entry.get("prev") != prev:
                return False, count, f"line {count} does not follow the previous entry"
            expected = hashlib.sha256((prev + canonical(entry)).encode("utf-8")).hexdigest()
            if recorded != expected:
                return False, count, f"line {count} hash mismatch"
            prev = expected
        return True, count, None


@dataclass
class Account:
    user_id: str
    salt: str
    hash: str
    params: dict[str, int] = field(default_factory=dict)
    display: str = ""
    login: str = ""
    nodes: list[str] = field(default_factory=list)
    created: float = 0.0
    last_login: float = 0.0
    failures: int = 0
    locked_until: float = 0.0

    def public(self) -> dict[str, Any]:
        """Everything an operator may see — deliberately never the hash."""
        return {
            "user_id": self.user_id,
            "display": self.display,
            "login": self.login,
            "nodes": list(self.nodes),
            "created": self.created,
            "last_login": self.last_login,
            "locked": self.locked_until > now(),
        }


class AuthService:
    def __init__(self, store: Path = STATE_DIR, resolver: IdentityResolver | None = None):
        self.store = Path(store)
        self.accounts_path = self.store / ACCOUNTS_FILE
        self.audit = AuditLog(self.store / AUDIT_FILE)
        self.admin_path = self.store / ADMIN_FILE
        self.resolver = resolver or IdentityResolver()
        self._accounts: dict[str, Account] = {}
        self._load()

    # ---- disk

    def _load(self) -> None:
        if not self.accounts_path.exists():
            self._accounts = {}
            return
        raw = json.loads(self.accounts_path.read_text(encoding="utf-8"))
        self._accounts = {uid: Account(**record) for uid, record in raw.get("users", {}).items()}

    def _save(self) -> None:
        self.store.mkdir(parents=True, exist_ok=True)
        os.chmod(self.store, 0o700)
        payload = {"version": 1, "users": {uid: asdict(acc) for uid, acc in self._accounts.items()}}
        handle = tempfile.NamedTemporaryFile("w", dir=self.store, delete=False, encoding="utf-8")
        try:
            json.dump(payload, handle, indent=2, sort_keys=True)
            handle.flush()
            os.fsync(handle.fileno())
        finally:
            handle.close()
        os.chmod(handle.name, 0o600)
        os.replace(handle.name, self.accounts_path)

    def admin_token(self) -> str:
        if self.admin_path.exists():
            return self.admin_path.read_text(encoding="utf-8").strip()
        self.store.mkdir(parents=True, exist_ok=True)
        os.chmod(self.store, 0o700)
        token = secrets.token_urlsafe(32)
        self.admin_path.write_text(token + "\n", encoding="utf-8")
        os.chmod(self.admin_path, 0o600)
        self.audit.append("admin-token-created")
        return token

    def check_admin(self, token: str) -> bool:
        return bool(token) and hmac.compare_digest(self.admin_token(), token)

    # ---- operations

    def identify(self, ip: str) -> Identity:
        return self.resolver.resolve(ip)

    def enroll(self, ip: str, display: str = "") -> dict[str, Any]:
        """First contact for an identity: mint the password this player will keep."""
        identity = self.identify(ip)
        existing = self._accounts.get(identity.user_id)
        if existing:
            self._remember_node(existing, identity)
            self._save()
            return {
                "status": "exists",
                "user_id": identity.user_id,
                "display": existing.display,
                "node": identity.node_id,
                "message": "this identity already has an account — use the password you saved",
            }
        secret = new_secret()
        salt, digest, params = hash_secret(secret)
        account = Account(
            user_id=identity.user_id,
            salt=salt,
            hash=digest,
            params=params,
            display=(display or identity.display_default)[:24],
            login=identity.login,
            nodes=[identity.node_id],
            created=now(),
        )
        self._accounts[identity.user_id] = account
        self._save()
        self.audit.append("enroll", user_id=identity.user_id, node=identity.node_id, login=identity.login)
        return {
            "status": "created",
            "user_id": identity.user_id,
            "display": account.display,
            "secret": secret,
            "message": "copy this password now and keep it somewhere safe — it is shown once",
        }

    def verify(self, ip: str, secret: str) -> dict[str, Any]:
        identity = self.identify(ip)
        account = self._accounts.get(identity.user_id)
        if account is None:
            self.audit.append("login-no-account", user_id=identity.user_id, node=identity.node_id)
            return {"status": "enroll", "user_id": identity.user_id,
                    "message": "no account for this identity yet"}
        if account.locked_until > now():
            self.audit.append("login-locked", user_id=identity.user_id, node=identity.node_id)
            return {"status": "locked", "user_id": identity.user_id,
                    "retry_after": round(account.locked_until - now(), 1)}
        if not check_secret(secret.strip(), account.salt, account.hash, account.params):
            account.failures += 1
            if account.failures >= FAIL_LIMIT:
                account.locked_until = now() + LOCKOUT_BASE_SECONDS * (2 ** (account.failures - FAIL_LIMIT))
            self._save()
            self.audit.append("login-failed", user_id=identity.user_id, node=identity.node_id,
                              failures=account.failures)
            locked = account.locked_until > now()
            return {
                "status": "locked" if locked else "denied",
                "user_id": identity.user_id,
                "failures": account.failures,
                "retry_after": round(account.locked_until - now(), 1) if locked else 0,
                "message": "too many wrong passwords — locked out for a while" if locked else "wrong password",
            }
        account.failures = 0
        account.locked_until = 0.0
        account.last_login = now()
        self._remember_node(account, identity)
        self._save()
        self.audit.append("login-ok", user_id=identity.user_id, node=identity.node_id)
        return {"status": "ok", "user_id": identity.user_id, "display": account.display}

    def _remember_node(self, account: Account, identity: Identity) -> None:
        if identity.node_id and identity.node_id not in account.nodes:
            account.nodes.append(identity.node_id)
        if identity.login and not account.login:
            account.login = identity.login

    def status(self) -> dict[str, Any]:
        ok, count, problem = self.audit.verify()
        return {
            "store": str(self.store),
            "accounts": [acc.public() for acc in sorted(self._accounts.values(), key=lambda a: a.display)],
            "audit": {"ok": ok, "entries": count, "problem": problem},
        }

    def admin_reset(self, token: str, user_id: str) -> dict[str, Any]:
        """Re-mint a password for an identity — the recovery path when someone loses theirs."""
        if not self.check_admin(token):
            self.audit.append("admin-reset-refused")
            return {"status": "forbidden"}
        account = self._accounts.get(user_id)
        if account is None:
            return {"status": "unknown", "user_id": user_id}
        secret = new_secret()
        salt, digest, params = hash_secret(secret)
        account.salt, account.hash, account.params = salt, digest, params
        account.failures = 0
        account.locked_until = 0.0
        self._save()
        self.audit.append("admin-reset", user_id=user_id)
        return {"status": "reset", "user_id": user_id, "display": account.display, "secret": secret}


# ---------------------------------------------------------------- cli


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Kingdom of Science tailnet accounts")
    parser.add_argument("--store", default=str(STATE_DIR), help="state directory")
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("identify", help="resolve the tailnet identity for an IP")
    p.add_argument("--ip", required=True)

    p = sub.add_parser("enroll", help="first-time registration (mints a password)")
    p.add_argument("--ip", required=True)
    p.add_argument("--display", default="")

    p = sub.add_parser("verify", help="check a password for the identity on this IP")
    p.add_argument("--ip", required=True)
    p.add_argument("--secret", required=True)

    sub.add_parser("status", help="accounts (no secrets) and audit integrity")

    p = sub.add_parser("admin-reset", help="re-mint a password for a user_id")
    p.add_argument("--user-id", required=True)
    p.add_argument("--token", default="")

    sub.add_parser("audit-verify", help="verify the audit hash chain")

    p = sub.add_parser("admin-token", help="print (creating if needed) the admin token")
    p.add_argument("--quiet", action="store_true")

    return parser


def main(argv: Iterable[str] | None = None) -> int:
    args = build_parser().parse_args(list(argv) if argv is not None else None)
    service = AuthService(Path(args.store))
    try:
        if args.command == "identify":
            identity = service.identify(args.ip)
            print(canonical({"status": "ok", **asdict(identity), "display_default": identity.display_default}))
        elif args.command == "enroll":
            print(canonical(service.enroll(args.ip, args.display)))
        elif args.command == "verify":
            print(canonical(service.verify(args.ip, args.secret)))
        elif args.command == "status":
            print(json.dumps(service.status(), indent=2, sort_keys=True))
        elif args.command == "audit-verify":
            ok, count, problem = service.audit.verify()
            print(canonical({"ok": ok, "entries": count, "problem": problem}))
        elif args.command == "admin-reset":
            print(canonical(service.admin_reset(args.token or service.admin_token(), args.user_id)))
        elif args.command == "admin-token":
            if not args.quiet:
                print(service.admin_token())
            else:
                service.admin_token()
    except IdentityError as exc:
        print(canonical({"status": "error", "reason": str(exc)}))
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
